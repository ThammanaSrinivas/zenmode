package com.zenlauncher.zenmode.coreapi

/**
 * The four buckets the Zen Score screen groups app usage into. Collapsed from Android's own
 * (much finer, and often-undeclared) [android.content.pm.ApplicationInfo.category] — see
 * [AppCategoryClassifier].
 */
enum class AppCategory { FOCUS, ENTERTAINMENT, COMMUNICATION, OTHER }
